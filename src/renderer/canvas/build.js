// ─── src/renderer/canvas/build.js ────────────────────────────────────────────
// Concatenates the canvas modules into one browser-loadable bundle.
//
// The modules are plain CommonJS so they can be require()d from Node for the
// headless tests in test/. Browsers have no require(), and the renderer may
// run under contextIsolation where Node globals are unavailable, so this emits
// a self-contained IIFE with a ~20-line module registry rather than pulling in
// a bundler and a dependency tree.
//
// Usage:  node src/renderer/canvas/build.js [outfile]
// ─────────────────────────────────────────────────────────────────────────────

const fs = require("fs");
const path = require("path");

// Dependency order matters: a module's factory runs on first require().
const MODULES = [
  "lru.js",
  "textlayout.js",
  "classify.js",
  "tokens.js",
  "lod.js",
  "viewport.js",
  "layout.js",
  "calendar.js",
  "describe.js",
  "imagecache.js",
  "texturecache.js",
  "renderer2d.js",
  "controls.js",
  "timelinestrip.js",
  "index.js",
];

function build(outFile) {
  const dir = __dirname;
  const parts = [];

  parts.push(`// ClipCanvas Time Canvas -- generated by src/renderer/canvas/build.js
// Do not edit directly; edit the modules in src/renderer/canvas/ and rebuild.
(function (global) {
  "use strict";
  var __defs = {}, __cache = {};
  function require(name) {
    var key = String(name).replace(/^\\.\\//, "").replace(/\\.js$/, "");
    if (__cache[key]) return __cache[key].exports;
    var def = __defs[key];
    if (!def) throw new Error("module not found: " + name);
    var m = { exports: {} };
    __cache[key] = m;
    def(m, m.exports, require);
    return m.exports;
  }
  function define(key, fn) { __defs[key] = fn; }
`);

  for (const file of MODULES) {
    const key = file.replace(/\.js$/, "");
    const src = fs.readFileSync(path.join(dir, file), "utf8");
    parts.push(`\n  define(${JSON.stringify(key)}, function (module, exports, require) {\n`);
    parts.push(src.split("\n").map((l) => (l ? "    " + l : "")).join("\n"));
    parts.push("\n  });\n");
  }

  parts.push(`
  global.ClipCanvasTimeCanvas = require("index");
  global.ClipCanvasInternals = {
    layout: require("layout"),
    textlayout: require("textlayout"),
    classify: require("classify"),
    tokens: require("tokens"),
    describe: require("describe"),
    lod: require("lod"),
    viewport: require("viewport"),
    renderer2d: require("renderer2d"),
  };
})(typeof window !== "undefined" ? window : globalThis);
`);

  const out = parts.join("");
  fs.writeFileSync(outFile, out, "utf8");
  return out.length;
}

if (require.main === module) {
  const out = process.argv[2] || path.join(__dirname, "..", "..", "..", "demo", "timecanvas.bundle.js");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const bytes = build(out);
  console.log(`built ${out} (${(bytes / 1024).toFixed(1)} KB)`);
}

module.exports = { build, MODULES };
